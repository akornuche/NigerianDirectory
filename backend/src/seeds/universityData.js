/**
 * Build a URL slug from an institution name.
 *
 * Matches the slugs already present in existing databases so that re-seeding
 * updates rows instead of creating duplicates.
 */
function slugify(name) {
    return name
        .toLowerCase()
        .replace(/[,.]/g, '')
        .replace(/\s+/g, '-');
}

