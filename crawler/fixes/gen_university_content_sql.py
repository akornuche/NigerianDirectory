"""
Generate SQL that replaces the profile text of every published university with
original text written from verified facts (crawler/content/universities_<date>/).

Before this, university profiles held text copied from the universities' own
websites and from listing sites. Each batch file maps a record id to:
  h    overview and history     -> enriched_history
  a    academics                -> enriched_academics (an admission note is appended)
  c    campus and location      -> enriched_campus_info
  src  which source the facts came from (wiki, site or nuc)
sources.json lists the cited URLs per record. Student-life text, which was
copied promotional copy throughout, is cleared.

The SQL also writes a factual meta title and description, and retires record
287 (Kogi State University), a duplicate of 505 (Prince Abubakar Audu
University), with a slug alias so the old URL redirects.

Only records that are verified universities are touched. One transaction.

Usage: python crawler/fixes/gen_university_content_sql.py crawler/content/universities_2026-11-23 > out.sql
"""
import glob
import json
import os
import sys

DUPLICATES = {287: 505}  # retired id -> surviving id

TYPE_WORD = {'federal': 'federal', 'state': 'state', 'private': 'private'}

ADMISSION = {
    'federal': (
        'Admission to undergraduate programmes is through the Joint Admissions and Matriculation Board (JAMB). '
        'Candidates sit the Unified Tertiary Matriculation Examination (UTME) and need at least five O-level credits, '
        'including English Language and Mathematics, in WAEC, NECO or equivalent examinations. Most federal universities '
        'also run their own post-UTME screening. Cut-off marks and requirements vary by course and year, so confirm them '
        'with the university and JAMB before applying.'
    ),
    'state': (
        'Undergraduate admission is through JAMB: applicants take the UTME, and need five O-level credits including '
        'English Language and Mathematics. Like other state universities, it may give some preference to applicants from '
        'its home state within national admission guidelines. Check current cut-off marks and screening dates with the '
        'university and JAMB.'
    ),
    'private': (
        'As at every Nigerian university, undergraduate admission goes through JAMB, so applicants must sit the UTME or '
        'apply by direct entry, and need five O-level credits including English Language and Mathematics. Private '
        'universities set their own tuition fees, which are usually higher than at public universities; ask the '
        'university for the current fees and any screening requirements.'
    ),
}
OPEN_ADMISSION = (
    'Admission still goes through JAMB, but open and distance learning universities usually have more flexible entry '
    'routes for working adults. Confirm requirements and study-centre arrangements with the university.'
)


def q(value):
    if value is None:
        return 'NULL'
    return "'" + str(value).replace("'", "''") + "'"


def admission_note(name, utype):
    if 'Open University' in name:
        return OPEN_ADMISSION
    return ADMISSION.get(utype, ADMISSION['private'])


def meta_title(name, utype, state):
    t = f'{name}: {utype.capitalize()} University in {state}'
    if len(t) <= 60:
        return t
    t = f'{name}, {state}'
    return t if len(t) <= 60 else name[:60]


def meta_description(name, utype, city, state, year):
    where = f'{city}, {state}' if city and city != state else state
    since = f', founded in {year}' if year else ''
    d = f'{name} is a {utype} university in {where}{since}. History, location, programmes and how admission works, with sources.'
    if len(d) > 160:
        d = f'{name}: {utype} university in {where}{since}. History, location and admission.'
    return d[:160]


def main(folder):
    content = {}
    # batchNN files hold the first rewrite; expandNN files (written later
    # from the full Wikipedia articles) replace entries for the same ids.
    for pattern in ('batch*.json', 'expand*.json'):
        for path in sorted(glob.glob(os.path.join(folder, pattern))):
            content.update(json.load(open(path)))
    sources = {k: v for k, v in json.load(open(os.path.join(folder, 'sources.json'))).items() if not k.startswith('_')}
    facts = json.load(open(os.path.join(folder, 'facts.json')))

    out = [
        f'-- Generated by crawler/fixes/gen_university_content_sql.py from {folder}.',
        '-- Replaces copied university profile text with original text from verified facts.',
        'BEGIN;',
    ]
    for key in sorted(content, key=int):
        rid = int(key)
        if rid in DUPLICATES:
            continue
        e, f = content[key], facts[key]
        academics = (e['a'].strip() + '\n\n' + admission_note(f['name'], f['type'])).strip()
        cs = [{'url': u, 'type': 'wikipedia' if 'wikipedia.org' in u else 'nuc' if 'nuc.edu.ng' in u else 'official_website'}
              for u in sources[key]]
        out.append(
            'UPDATE schools SET '
            f"enriched_history = {q(e['h'].strip())}, "
            f'enriched_academics = {q(academics)}, '
            f"enriched_campus_info = {q(e['c'].strip())}, "
            'enriched_student_life = NULL, '
            f'content_sources = {q(json.dumps(cs))}::jsonb, '
            f"meta_title = {q(meta_title(f['name'], f['type'], f['state']))}, "
            f"meta_description = {q(meta_description(f['name'], f['type'], f['city'], f['state'], f['founded']))}, "
            'enriched_at = NOW(), updated_at = NOW() '
            f"WHERE id = {rid} AND institution_category = 'university' AND verification_status = 'verified';"
        )
    for old, new in DUPLICATES.items():
        out.append(
            "INSERT INTO slug_aliases (old_slug, school_id, reason) "
            f"SELECT slug, {new}, 'duplicate of {new} (renamed in 2020)' FROM schools WHERE id = {old} "
            'ON CONFLICT (old_slug) DO UPDATE SET school_id = EXCLUDED.school_id, reason = EXCLUDED.reason;'
        )
        out.append(
            "UPDATE schools SET verification_status = 'rejected', "
            f"verification_notes = 'Not published: duplicate of record {new} (same institution, renamed)', updated_at = NOW() "
            f'WHERE id = {old};'
        )
    out.append('COMMIT;')
    print('\n'.join(out))


if __name__ == '__main__':
    main(sys.argv[1])
