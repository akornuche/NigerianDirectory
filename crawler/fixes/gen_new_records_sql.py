"""
Generate SQL that inserts new, already-verified directory records with
original profiles, from a JSON file in crawler/content/.

Each entry is one institution:
  category        'university' or 'school'
  name, type, state, city, area (schools), website, established_year,
  gender, boarding (optional)
  source_name, source_url   the independent source that confirms it exists
  sources         URLs cited on the page (content_sources)
  h, a, c, s      overview/history, academics, campus/location, student life

Universities get the standard JAMB admission note appended to the academics
section and the same meta title and description rules as
gen_university_content_sql.py. Inserts are idempotent: a slug that already
exists is left untouched (ON CONFLICT DO NOTHING).

Usage: python crawler/fixes/gen_new_records_sql.py crawler/content/new_records_2026-11-24.json > out.sql
       add --update to refresh the profile text of records that already exist
       (matched by slug) instead of inserting them.
"""
import json
import os
import re
import sys
import unicodedata

sys.path.insert(0, os.path.dirname(__file__))
from gen_university_content_sql import admission_note, meta_description, meta_title  # noqa: E402


def q(v):
    if v is None:
        return 'NULL'
    if isinstance(v, bool):
        return 'true' if v else 'false'
    if isinstance(v, int):
        return str(v)
    return "'" + str(v).replace("'", "''") + "'"


def slugify(name):
    s = unicodedata.normalize('NFKD', name).encode('ascii', 'ignore').decode().lower()
    s = s.replace('&', ' and ').replace("'", '')
    return re.sub(r'[^a-z0-9]+', '-', s).strip('-')


def school_meta(e):
    where = ', '.join(x for x in [e.get('area') or e.get('city'), e['state']] if x)
    first = (e.get('h') or '').split('. ')[0].rstrip('.')
    desc = (first + '.') if first else f"{e['name']} is a secondary school in {where}."
    return (f"{e['name']}, {e['state']}" if len(e['name']) + len(e['state']) < 58 else e['name'][:60]), desc[:158]


def main(path):
    data = {k: v for k, v in json.load(open(path)).items() if not k.startswith('_')}
    out = [f'-- Generated by crawler/fixes/gen_new_records_sql.py from {path}.', 'BEGIN;']
    for key, e in data.items():
        uni = e['category'] == 'university'
        academics = (e.get('a') or '').strip()
        if uni:
            academics = (academics + '\n\n' + admission_note(e['name'], e['type'])).strip()
            title = meta_title(e['name'], e['type'], e['state'])
            desc = meta_description(e['name'], e['type'], e['city'], e['state'], e.get('established_year'))
        else:
            title, desc = school_meta(e)
        cs = [{'url': u, 'type': 'wikipedia' if 'wikipedia.org' in u else 'nuc' if 'nuc.edu.ng' in u else 'official_website'}
              for u in e['sources']]
        fs = {'profile_text': e['sources'][0], 'existence': e['source_url']}
        if e.get('established_year'):
            fs['established_year'] = e['sources'][0]
        cols = {
            'name': e['name'], 'slug': e.get('slug') or slugify(e['name']), 'institution_category': e['category'],
            'type': e['type'], 'state': e['state'], 'city': e.get('city'), 'area': e.get('area'),
            'website': e.get('website'), 'established_year': e.get('established_year'),
            'gender': e.get('gender'), 'boarding': e.get('boarding'),
            'enriched_history': (e.get('h') or '').strip() or None, 'enriched_academics': academics or None,
            'enriched_campus_info': (e.get('c') or '').strip() or None, 'enriched_student_life': (e.get('s') or '').strip() or None,
            'meta_title': title, 'meta_description': desc,
            'verification_status': 'verified', 'verification_source_name': e['source_name'],
            'verification_source_url': e['source_url'],
            'verification_notes': f"Added from {e['source_name']}; reviewed by hand {e.get('reviewed', '2026-11-24')}",
        }
        names = list(cols) + ['content_sources', 'field_sources', 'data_verified_at', 'enriched_at', 'enrichment_status', 'needs_ai_enrichment']
        vals = [q(v) for v in cols.values()] + [q(json.dumps(cs)) + '::jsonb', q(json.dumps(fs)) + '::jsonb', 'NOW()', 'NOW()', "'completed'", 'false']
        if UPDATE:
            keep = ['enriched_history', 'enriched_academics', 'enriched_campus_info', 'enriched_student_life', 'meta_title', 'meta_description']
            sets = ', '.join(f"{c} = {q(cols[c])}" for c in keep)
            out.append(f"UPDATE schools SET {sets}, content_sources = {q(json.dumps(cs))}::jsonb, updated_at = NOW() WHERE slug = {q(cols['slug'])};")
        else:
            out.append(f"INSERT INTO schools ({', '.join(names)}) VALUES ({', '.join(vals)}) ON CONFLICT (slug) DO NOTHING;")
    out.append('COMMIT;')
    print('\n'.join(out))


UPDATE = '--update' in sys.argv

if __name__ == '__main__':
    main(sys.argv[1])
