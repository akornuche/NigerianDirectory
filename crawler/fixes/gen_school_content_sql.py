"""
Generate SQL that publishes the original school profiles in
crawler/content/schools_<date>.json.

Each entry holds sections written from the listed sources (a Wikipedia
article and the school's Wikidata item), optional field corrections from the
same sources ("set"), and the source URLs. The SQL:
  - writes the sections to enriched_history / _academics / _campus_info /
    _student_life (sections not written are cleared, never left stale);
  - applies "set" corrections (null clears a field whose sources conflict);
  - records the sources in content_sources and field_sources;
  - builds a short factual meta description from verified fields only.
It only touches records that are already verification_status = 'verified'.

Usage: python crawler/fixes/gen_school_content_sql.py crawler/content/schools_2026-11-22.json > out.sql
"""
import json
import sys

SECTION_FIELDS = {
    'history': 'enriched_history',
    'academics': 'enriched_academics',
    'campus_info': 'enriched_campus_info',
    'student_life': 'enriched_student_life',
}
SETTABLE = {'name', 'state', 'city', 'area', 'established_year', 'gender', 'type', 'website', 'boarding'}


def q(value):
    if value is None:
        return 'NULL'
    if isinstance(value, bool):
        return 'true' if value else 'false'
    if isinstance(value, int):
        return str(value)
    return "'" + str(value).replace("'", "''") + "'"


def main(path):
    data = json.load(open(path))
    out = [f"-- Generated by crawler/fixes/gen_school_content_sql.py from {path}.",
           "-- Publishes original, source-cited profiles for verified schools.", ""]
    for key, entry in sorted(((k, v) for k, v in data.items() if not k.startswith('_')), key=lambda kv: int(kv[0])):
        sources = entry['sources']
        sets = []
        for section, column in SECTION_FIELDS.items():
            text = (entry.get(section) or '').strip()
            sets.append(f"{column} = {q(text or None)}")
        corrections = entry.get('set', {})
        unknown = set(corrections) - SETTABLE
        if unknown:
            raise SystemExit(f'{key}: cannot set {sorted(unknown)}')
        for field, value in corrections.items():
            sets.append(f"{field} = {q(value)}")
        if 'established_year' in entry:
            sets.append(f"established_year = {q(entry['established_year'])}")
        content_sources = [{'url': u, 'type': 'wikipedia' if 'wikipedia.org' in u else 'reference'} for u in sources]
        sets.append(f"content_sources = {q(json.dumps(content_sources))}::jsonb")
        field_src = {f: sources[0] for f in corrections}
        if 'established_year' in entry:
            field_src['established_year'] = sources[0]
        field_src['profile_text'] = sources[0]
        sets.append(f"field_sources = field_sources || {q(json.dumps(field_src))}::jsonb")
        # Meta description from the first sentence of the history section: it
        # is our own wording and states verified facts.
        first = (entry.get('history') or entry.get('academics') or '').split('. ')[0].strip().rstrip('.')
        if first:
            meta = (first + '.')[:158]
            sets.append(f"meta_description = {q(meta)}")
        sets.append("updated_at = NOW()")
        out.append(f"UPDATE schools SET {', '.join(sets)} WHERE id = {int(key)} "
                   f"AND institution_category = 'school' AND verification_status = 'verified';")
    print('\n'.join(out))


if __name__ == '__main__':
    main(sys.argv[1])
